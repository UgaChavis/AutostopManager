"""Keep claim rollback, durable-result recovery and batching boundaries covered.

All cases use a private temporary SQLite database. SQL failures before commit
must roll back the job, event bindings and generation together. Errors after
commit leave a durable claim that can be discovered and explicitly released.

A separate reservation-only SQLite connection models storage contention while
preserving the inbox process's exclusive ownership contract.
"""

from __future__ import annotations

import sqlite3
from datetime import UTC, datetime, timedelta
from pathlib import Path
from typing import Any

import pytest

from autostop_manager.telegram_inbox import InboxError, TelegramInbox


ROOT = "/opt/synthetic-iteration-017"
REVISION = "a" * 40
NOW = datetime(2026, 10, 16, 9, 0, 0, tzinfo=UTC)


@pytest.fixture
def queue(tmp_path: Path):
    with TelegramInbox(tmp_path / "claim-017" / "inbound.sqlite3", clock=lambda: NOW) as inbox:
        inbox.duty_set(True)
        yield inbox


def _claim(queue: TelegramInbox, **kwargs: Any) -> dict[str, Any] | None:
    return queue.claim(instruction_root=ROOT, instruction_revision=REVISION, **kwargs)


def _record(queue: TelegramInbox, peer: int, message: int, at: str | None = None) -> str:
    event_id = queue.record(peer, message, received_at=at)
    assert isinstance(event_id, str)
    return event_id


def _two_events(queue: TelegramInbox) -> list[str]:
    return [_record(queue, 17, 1), _record(queue, 17, 2)]


def _snapshot(queue: TelegramInbox) -> dict[str, Any]:
    return {
        "generation": queue.generation,
        "jobs": [tuple(row) for row in queue._db.execute("SELECT * FROM jobs ORDER BY rowid")],
        "events": [tuple(row) for row in queue._db.execute("SELECT * FROM events ORDER BY rowid")],
        "peers": [tuple(row) for row in queue._db.execute("SELECT * FROM peers ORDER BY peer_id")],
        "effects": [tuple(row) for row in queue._db.execute("SELECT * FROM effects ORDER BY rowid")],
        "boundary_holds": [tuple(row) for row in queue._db.execute("SELECT * FROM boundary_holds ORDER BY rowid")],
        "peer_threads": [tuple(row) for row in queue._db.execute("SELECT * FROM peer_threads ORDER BY peer_id")],
        "global_slot": [tuple(row) for row in queue._db.execute("SELECT * FROM global_slot")],
    }


def _assert_bindings(queue: TelegramInbox, event_ids: list[str], job_id: str | None) -> None:
    for event_id in event_ids:
        row = queue._db.execute(
            "SELECT state,job_id FROM events WHERE sequence=?", (event_id.removeprefix("inbound-"),)
        ).fetchone()
        assert row is not None
        assert tuple(row) == ("open", job_id)


def _assert_recoverable_claim(queue: TelegramInbox, event_ids: list[str], previous_generation: int) -> None:
    assert queue._db.in_transaction is False
    active = queue.active_jobs()
    assert len(active) == 1
    job = active[0]
    assert job["state"] == "claimed"
    assert job["event_ids"] == event_ids
    assert job["thread_id"] is None and job["turn_id"] is None
    assert job["effects"] == []
    assert queue.generation == previous_generation + 1
    _assert_bindings(queue, event_ids, job["job_id"])

    committed = _snapshot(queue)
    assert _claim(queue) is None
    assert _snapshot(queue) == committed

    released = queue.release_job(job_id=job["job_id"], lease=job["lease"], expected_revision=job["revision"])
    assert released["state"] == "released"
    assert released["event_ids"] == []
    _assert_bindings(queue, event_ids, None)
    assert queue.active_jobs() == []

    replacement = _claim(queue)
    assert replacement is not None
    assert replacement["job_id"] != job["job_id"]
    assert replacement["event_ids"] == event_ids
    assert len(queue.active_jobs()) == 1


def test_second_event_update_failure_rolls_back_the_whole_claim(queue: TelegramInbox) -> None:
    event_ids = _two_events(queue)
    sequences = [event_id.removeprefix("inbound-") for event_id in event_ids]
    # The identities are generated by record(), not user-controlled SQL.
    assert all(sequence.isascii() and sequence.isdigit() for sequence in sequences)
    before = _snapshot(queue)
    attempted: list[str] = []
    # This callback observes attempted UPDATE order; it has no database writes.
    # Its Python list intentionally survives the injected transaction rollback.
    queue._db.create_function("synthetic_claim_update", 1, attempted.append)
    queue._db.execute(
        "CREATE TRIGGER synthetic_fail_second_claim BEFORE UPDATE OF job_id ON events "
        "WHEN NEW.job_id IS NOT NULL BEGIN "
        "SELECT synthetic_claim_update(OLD.sequence); "
        f"SELECT RAISE(ABORT, 'synthetic_second_update') WHERE OLD.sequence='{sequences[1]}'; END"
    )
    queue._db.commit()

    with pytest.raises(InboxError, match=r"^inbox_storage_failed$"):
        _claim(queue)

    assert attempted == sequences
    assert queue._db.in_transaction is False
    assert _snapshot(queue) == before
    _assert_bindings(queue, event_ids, None)

    queue._db.execute("DROP TRIGGER synthetic_fail_second_claim")
    queue._db.commit()
    retried = _claim(queue)
    assert retried is not None and retried["event_ids"] == event_ids
    assert queue.generation == before["generation"] + 1
    assert len(queue.active_jobs()) == 1


def test_generation_update_failure_rolls_back_job_and_all_event_bindings(queue: TelegramInbox) -> None:
    event_ids = _two_events(queue)
    sequences = [event_id.removeprefix("inbound-") for event_id in event_ids]
    before = _snapshot(queue)
    attempted: list[str] = []
    queue._db.create_function("synthetic_claim_update", 1, attempted.append)
    queue._db.execute(
        "CREATE TRIGGER synthetic_trace_claim BEFORE UPDATE OF job_id ON events "
        "WHEN NEW.job_id IS NOT NULL BEGIN SELECT synthetic_claim_update(OLD.sequence); END"
    )
    queue._db.execute(
        "CREATE TRIGGER synthetic_fail_generation BEFORE UPDATE OF value ON metadata "
        "WHEN OLD.key='generation' BEGIN SELECT RAISE(ABORT, 'synthetic_generation'); END"
    )
    queue._db.commit()

    with pytest.raises(InboxError, match=r"^inbox_storage_failed$"):
        _claim(queue)

    assert attempted == sequences
    assert queue._db.in_transaction is False
    assert _snapshot(queue) == before
    _assert_bindings(queue, event_ids, None)

    queue._db.execute("DROP TRIGGER synthetic_fail_generation")
    queue._db.execute("DROP TRIGGER synthetic_trace_claim")
    queue._db.commit()
    retried = _claim(queue)
    assert retried is not None and retried["event_ids"] == event_ids
    assert queue.generation == before["generation"] + 1
    assert len(queue.active_jobs()) == 1


def test_secure_files_failure_after_commit_leaves_one_recoverable_claim(queue: TelegramInbox, monkeypatch) -> None:
    event_ids = _two_events(queue)
    before_generation = queue.generation
    injected_calls = 0

    def injected_failure() -> None:
        nonlocal injected_calls
        injected_calls += 1
        assert queue._db.in_transaction is False
        assert queue.generation == before_generation + 1
        raise InboxError("inbox_file_invalid")

    # This is artificial post-commit filesystem validation failure, not proof of
    # a real permission problem or a rollback guarantee for post-commit errors.
    with monkeypatch.context() as patch:
        patch.setattr(queue, "_secure_files", injected_failure)
        with pytest.raises(InboxError, match=r"^inbox_file_invalid$"):
            _claim(queue)

    assert injected_calls == 1
    _assert_recoverable_claim(queue, event_ids, before_generation)


def test_result_read_failure_after_commit_does_not_allow_a_second_claim(queue: TelegramInbox, monkeypatch) -> None:
    event_ids = _two_events(queue)
    before_generation = queue.generation
    observed_job_ids: list[str] = []

    def injected_read_failure(job_id: str) -> dict[str, Any]:
        observed_job_ids.append(job_id)
        assert queue._db.in_transaction is False
        assert queue.generation == before_generation + 1
        raise InboxError("inbox_storage_failed")

    # read_job is after _write has committed. A caller error therefore does not
    # establish that no claim exists; the active registry is the recovery path.
    with monkeypatch.context() as patch:
        patch.setattr(queue, "read_job", injected_read_failure)
        with pytest.raises(InboxError, match=r"^inbox_storage_failed$"):
            _claim(queue)

    assert len(observed_job_ids) == 1
    assert queue.active_jobs()[0]["job_id"] == observed_job_ids[0]
    _assert_recoverable_claim(queue, event_ids, before_generation)


def test_busy_begin_immediate_does_not_reserve_events(queue: TelegramInbox) -> None:
    event_ids = _two_events(queue)
    before = _snapshot(queue)
    original_busy_timeout = queue._db.execute("PRAGMA busy_timeout").fetchone()[0]
    holder = sqlite3.connect(queue.path, timeout=0)
    try:
        queue._db.execute("PRAGMA busy_timeout=0")
        holder.execute("BEGIN IMMEDIATE")
        assert holder.in_transaction is True
        # The holder never writes a row or bypasses the single-owner contract.
        with pytest.raises(InboxError, match=r"^inbox_storage_failed$"):
            _claim(queue)
        assert queue._db.in_transaction is False
        assert _snapshot(queue) == before
        assert holder.total_changes == 0
    finally:
        holder.rollback()
        holder.close()
        queue._db.execute(f"PRAGMA busy_timeout={int(original_busy_timeout)}")

    retried = _claim(queue)
    assert retried is not None and retried["event_ids"] == event_ids
    assert queue.generation == before["generation"] + 1
    assert len(queue.active_jobs()) == 1


@pytest.mark.parametrize(
    ("microseconds", "included"),
    [pytest.param(0, True, id="exactly-300-seconds"), pytest.param(1, False, id="300-seconds-plus-1us")],
)
def test_batch_window_has_an_inclusive_exact_cutoff(queue: TelegramInbox, microseconds: int, included: bool) -> None:
    first = _record(queue, 17, 1)
    cutoff = NOW + timedelta(seconds=300, microseconds=microseconds)
    second = _record(queue, 17, 2, cutoff.isoformat())
    before_generation = queue.generation

    job = _claim(queue)

    assert job is not None
    assert job["event_ids"] == ([first, second] if included else [first])
    assert queue.generation == before_generation + 1
    _assert_bindings(queue, [first], job["job_id"])
    _assert_bindings(queue, [second], job["job_id"] if included else None)


def test_offset_timestamps_use_utc_window_and_chronological_order(queue: TelegramInbox) -> None:
    # Record the later item first to distinguish chronological selection from
    # arrival order; all timestamps represent the same synthetic UTC window.
    inside = _record(queue, 17, 2, "2026-10-16T04:04:00-05:00")
    first = _record(queue, 17, 1, "2026-10-16T16:00:00+07:00")
    boundary = _record(queue, 17, 3, "2026-10-16T11:05:00+02:00")
    outside = _record(queue, 17, 4, "2026-10-16T06:05:00.000001-03:00")

    job = _claim(queue)

    assert job is not None and job["event_ids"] == [first, inside, boundary]
    _assert_bindings(queue, [first, inside, boundary], job["job_id"])
    _assert_bindings(queue, [outside], None)


def test_equal_timestamps_keep_fifo_tie_order_and_do_not_mix_peers(queue: TelegramInbox) -> None:
    first = _record(queue, 17, 20)
    different_peer = _record(queue, 18, 1)
    next_same_peer = _record(queue, 17, 10)

    job = _claim(queue)

    assert job is not None and job["event_ids"] == [first, next_same_peer]
    assert job["peer_id"] == 17
    _assert_bindings(queue, [different_peer], None)
    before = _snapshot(queue)
    assert _claim(queue) is None
    assert _snapshot(queue) == before


def test_same_sender_keeps_five_item_limit_and_remaining_events_unbound(queue: TelegramInbox) -> None:
    event_ids = [_record(queue, 17, message) for message in range(1, 7)]

    job = _claim(queue)

    assert job is not None and job["event_ids"] == event_ids[:5]
    _assert_bindings(queue, event_ids[:5], job["job_id"])
    _assert_bindings(queue, event_ids[5:], None)
